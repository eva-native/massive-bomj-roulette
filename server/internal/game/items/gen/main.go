// Command gen writes texts_gen.go from docs/rules: the name, kind and rule
// text of every item, so the catalog never duplicates the documents.
//
// Usage (from the items package, see go:generate in catalog.go):
//
//	go run ./gen ../../../../docs/rules texts_gen.go
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var (
	headingRe = regexp.MustCompile(`^### (.+)$`)
	idRe      = regexp.MustCompile("^`([a-z0-9_]+)`")
)

type text struct{ id, kind, name, concept string }

// files maps each rules document to the item kind it lists.
var files = []struct{ name, kind string }{
	{"effects.md", "KindEffect"},
	{"bonuses.md", "KindBonus"},
	{"drop-debuffs.md", "KindDrop"},
}

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen <docs/rules dir> <output.go>")
		os.Exit(2)
	}
	var all []text
	for _, f := range files {
		items, err := parse(filepath.Join(os.Args[1], f.name), f.kind)
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		all = append(all, items...)
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by ./gen from docs/rules. DO NOT EDIT.\n\npackage items\n\n")
	b.WriteString("import \"github.com/eva-native/massive-bomj-roulette/server/internal/game\"\n\n")
	b.WriteString("// texts holds the name, kind and rule text of every item in docs/rules.\n")
	b.WriteString("var texts = map[string]itemText{\n")
	for _, t := range all {
		fmt.Fprintf(&b, "\t%q: {Kind: game.%s, Name: %q, Concept: %q},\n", t.id, t.kind, t.name, t.concept)
	}
	b.WriteString("}\n\n// textOrder lists item ids in the order of the documents.\nvar textOrder = []string{\n")
	for _, t := range all {
		fmt.Fprintf(&b, "\t%q,\n", t.id)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[2], src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// parse reads items from a rules document. An item is a "### Name" heading,
// a line starting with `id`, and the rule text up to the next heading.
func parse(path, kind string) ([]text, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var (
		out  []text
		cur  *text
		body []string
		name string
	)
	flush := func() {
		if cur != nil {
			cur.concept = strings.Join(body, "\n")
			out = append(out, *cur)
		}
		cur, body = nil, nil
	}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimRight(sc.Text(), " ")
		switch {
		case strings.HasPrefix(line, "#"):
			flush()
			name = ""
			if m := headingRe.FindStringSubmatch(line); m != nil {
				name = m[1]
			}
		case name != "" && cur == nil && idRe.MatchString(line):
			cur = &text{id: idRe.FindStringSubmatch(line)[1], kind: kind, name: name}
		case cur != nil && strings.TrimSpace(line) != "":
			body = append(body, strings.TrimSpace(line))
		}
	}
	flush()
	if err := sc.Err(); err != nil {
		return nil, err
	}
	for _, t := range out {
		if t.concept == "" {
			return nil, fmt.Errorf("%s: item %q has no rule text", path, t.id)
		}
	}
	return out, nil
}
