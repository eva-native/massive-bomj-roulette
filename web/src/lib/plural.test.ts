import { expect, it } from 'vitest'
import { plural } from './plural'

it('picks the Russian plural form', () => {
  const sectors = (n: number) => `${n} ${plural(n, 'сектор', 'сектора', 'секторов')}`
  expect([1, 2, 4, 5, 11, 12, 14, 21, 22, 37, 100, 101, 111, 112].map(sectors)).toEqual([
    '1 сектор',
    '2 сектора',
    '4 сектора',
    '5 секторов',
    '11 секторов',
    '12 секторов',
    '14 секторов',
    '21 сектор',
    '22 сектора',
    '37 секторов',
    '100 секторов',
    '101 сектор',
    '111 секторов',
    '112 секторов',
  ])
})
